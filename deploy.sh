echo "========================================"
echo "🚀 Запуск скрипта развертывания..."
echo "========================================"

# 1. Показать текущую директорию
echo "📁 Текущая директория:"
pwd

# 2. Показать статус git
echo ""
echo "📊 Статус git:"
git status

# 3. Добавить все изменения
echo ""
echo "📦 Добавляем все изменения..."
git add .

# 4. Сделать коммит с сообщением
echo ""
echo "💾 Создаем коммит..."
git commit -m "Автоматический деплой: $(date '+%Y-%m-%d %H:%M:%S')"

# 5. Отправить на GitHub
echo ""
echo "☁️  Отправляем на GitHub..."
git push

# 6. Показать последние коммиты
echo ""
echo "📋 Последние 3 коммита:"
git log --oneline -3

echo ""
echo "========================================"
echo "✅ Скрипт развертывания завершен!"
echo "========================================"
